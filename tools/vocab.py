#!/usr/bin/env python3
"""Writes docs/VOCAB.md: the allowed categories, roles and instruments, and every party id already in the graph.
Automated writers read it before minting anything. Regenerated by `make check`."""
import glob, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
onto = open(os.path.join(ROOT, "data", "ontology.ttl"), encoding="utf-8").read()
ents = {}
for f in sorted(glob.glob(os.path.join(ROOT, "data", "raw", "*.entities.jsonl"))):
    for l in open(f, encoding="utf-8"):
        if l.strip():
            r = json.loads(l); ents.setdefault(r["id"], r.get("label", ""))
out = ["# Vocabulary and party ids (generated; do not edit)", ""]
for title, pre in (("Event `category`", "cat"), ("Flow `instrument`", "instr"), ("Role `role`", "role")):
    out += ["## " + title, "", ", ".join("`%s`" % x for x in sorted(set(re.findall(r"^uc:%s_([a-z0-9_]+)" % pre, onto, re.M)))), ""]
out += ["## `prov.asserted_by`", "", "`prosecution`, `rey`, `defence`, `regulator`, `rating_agency`, `company`, `press`, `analyst`", "",
        "## Party ids already in the graph (%d)" % len(ents), "", "Reuse one of these before minting a new id.", "", "| id | label |", "|---|---|"]
out += ["| `%s` | %s |" % (i, (ents[i] or "").replace("|", "/")) for i in sorted(ents)]
open(os.path.join(ROOT, "docs", "VOCAB.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("docs/VOCAB.md:", len(ents), "party ids")
